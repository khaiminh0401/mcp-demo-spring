CREATE TABLE IF NOT EXISTS cab_rides (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ride_id VARCHAR(64) NOT NULL UNIQUE,
    pickup_location VARCHAR(200) NOT NULL,
    dropoff_location VARCHAR(200) NOT NULL,
    pickup_time VARCHAR(80) NOT NULL,
    passenger_name VARCHAR(150) NOT NULL,
    driver_name VARCHAR(150) NOT NULL,
    license_plate VARCHAR(30) NOT NULL,
    estimated_price DECIMAL(15, 2) NOT NULL,
    status VARCHAR(30) NOT NULL,
    booked_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);
